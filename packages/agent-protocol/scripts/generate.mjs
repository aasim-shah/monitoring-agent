// Generates TypeScript interfaces and Go structs from the agent protocol JSON Schemas.
// Usage: node scripts/generate.mjs [--check]
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { compile } from 'json-schema-to-typescript';

const root = new URL('../', import.meta.url);
const schemaDir = new URL('schemas/', root);
const tsOut = new URL('src/generated/types.ts', root);
const goOut = new URL('go/types.go', root);

const BANNER = 'Code generated by scripts/generate.mjs from schemas/*.schema.json. DO NOT EDIT.';

const schemas = readdirSync(schemaDir)
  .filter((f) => f.endsWith('.schema.json'))
  .sort()
  .map((f) => JSON.parse(readFileSync(new URL(f, schemaDir), 'utf8')));

async function generateTs() {
  const parts = [];
  for (const schema of schemas) {
    parts.push(
      await compile(schema, schema.title, { bannerComment: '', format: false, additionalProperties: false }),
    );
  }
  return `// ${BANNER}\n\n${parts.join('\n').trim()}\n`;
}

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

function goType(prop, nestedName, structs) {
  switch (prop.type) {
    case 'string':
      return 'string';
    case 'integer':
      return 'int64';
    case 'number':
      return 'float64';
    case 'boolean':
      return 'bool';
    case 'array':
      return `[]${goType(prop.items, nestedName, structs)}`;
    case 'object':
      if (prop.properties) {
        const name = prop.title ?? nestedName;
        structs.push(goStruct(name, prop, structs));
        return name;
      }
      if (prop.additionalProperties && prop.additionalProperties.type === 'string')
        return 'map[string]string';
      return 'map[string]any';
    default:
      throw new Error(`unsupported schema type ${prop.type}`);
  }
}

function goStruct(name, schema, structs) {
  const required = new Set(schema.required ?? []);
  const rows = Object.entries(schema.properties).map(([key, prop]) => {
    const type = goType(prop, `${name}${pascal(key)}`, structs);
    const tag = required.has(key) ? key : `${key},omitempty`;
    return [pascal(key), type, `\`json:"${tag}"\``];
  });
  // Align columns the way gofmt does: one space past the widest name and type.
  const nameWidth = Math.max(...rows.map(([n]) => n.length));
  const typeWidth = Math.max(...rows.map(([, t]) => t.length));
  const fields = rows.map(([n, t, tag]) => `\t${n.padEnd(nameWidth)} ${t.padEnd(typeWidth)} ${tag}`);
  return `type ${name} struct {\n${fields.join('\n')}\n}`;
}

function generateGo() {
  const structs = [];
  for (const schema of schemas) structs.push(goStruct(schema.title, schema, structs));
  return `// ${BANNER}\n\npackage agentprotocol\n\n${structs.join('\n\n')}\n`;
}

const outputs = [
  [tsOut, await generateTs()],
  [goOut, generateGo()],
];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([url, content]) => {
    try {
      return readFileSync(url, 'utf8') !== content;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`stale generated files: ${stale.map(([u]) => u.pathname).join(', ')}; run pnpm generate`);
    process.exit(1);
  }
} else {
  for (const [url, content] of outputs) writeFileSync(url, content);
}
