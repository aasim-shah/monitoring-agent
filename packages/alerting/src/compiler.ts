import { stringify } from 'yaml';
import { TEMPLATES, type Params, type Severity, type TemplateId } from './templates.js';

export interface CompiledRuleInput {
  id: string;
  productId: string | null;
  name: string;
  template: TemplateId;
  params: Params;
  severity: Severity;
  enabled: boolean;
}

/**
 * The vmalert file for one tenant (D17, WB-13 UC-13-01). Every group queries with
 * `extra_label=tenant_id=<org>`, so a rule can only ever see its own tenant's series
 * (BR-13-06). Product-scoped rules share a group per product that adds a product_id filter,
 * so expressions are never rewritten.
 */
export function compileTenant(
  orgId: string,
  rules: CompiledRuleInput[],
  opts: { interval?: string } = {},
): string {
  const interval = opts.interval ?? '1m';
  const scopes = new Map<string | null, CompiledRuleInput[]>();
  for (const r of rules) {
    const t = TEMPLATES[r.template];
    if (!r.enabled || t.kind !== 'metric') continue;
    scopes.set(r.productId, [...(scopes.get(r.productId) ?? []), r]);
  }
  const groups = [...scopes.entries()]
    .sort(([a], [b]) => (a ?? '').localeCompare(b ?? ''))
    .map(([productId, list]) => ({
      name: productId ? `tenant-${orgId}-product-${productId}` : `tenant-${orgId}`,
      interval,
      params: {
        extra_label: [`tenant_id=${orgId}`],
        ...(productId ? { extra_filters: [`{product_id="${productId}"}`] } : {}),
      },
      labels: { tenant_id: orgId, ...(productId ? { product_id: productId } : {}) },
      rules: list.map((r) => ({
        alert: `${r.template}-${r.id.slice(0, 8)}`,
        expr: TEMPLATES[r.template].expr!(r.params),
        for: `${r.params.forMinutes ?? 0}${r.params.forMinutes ? 'm' : 's'}`,
        labels: { rule_id: r.id, severity: r.severity },
        annotations: { summary: r.name, value: '{{ $value }}' },
      })),
    }));
  return `# Generated by the alert rule compiler (M12.1); do not edit.\n${stringify({ groups })}`;
}
